// sfizz internal parser API (static library target sfizz::parser, pinned sfizz 1.2.3).
#include "Defaults.h"
#include "Opcode.h"
#include "parser/Parser.h"
#include "parser/ParserListener.h"

#include <set>
#include <sstream>
#include <vector>

namespace drums::engine {
namespace {

class RoutingListener final : public sfz::ParserListener {
public:
    explicit RoutingListener(const std::array<int, 128>& outputForNote) : outputForNote_(outputForNote) {}

    void onParseFullBlock(const std::string& header, const std::vector<sfz::Opcode>& opcodes) override {
        // Same scoping rules as sfz::Synth::Impl::onParseFullBlock.
        if (header == "global") {
            global_ = opcodes;
            master_.clear();
            group_.clear();
        } else if (header == "master") {
            master_ = opcodes;
            group_.clear();
        } else if (header == "group") {
            group_ = opcodes;
        }
        if (header != "region") {
            emit(header, opcodes, nullptr);
            return;
        }
        routeRegion(opcodes);
    }

    void onParseError(const sfz::SourceRange&, const std::string& message) override { errors_.push_back(message); }

    std::ostringstream out;
    RoutedSfz stats;
    std::vector<std::string> errors_;

private:
    void routeRegion(const std::vector<sfz::Opcode>& opcodes) {
        ++stats.regions;
        // Effective key range, exactly like sfz::Region::parseOpcode applied global..region.
        int lo = sfz::Default::loKey, hi = sfz::Default::hiKey;
        bool onNote = true;
        auto apply = [&](const std::vector<sfz::Opcode>& list) {
            for (const auto& op : list) {
                if (op.name == "lokey") {
                    lo = op.read(sfz::Default::loKey);
                } else if (op.name == "hikey") {
                    const auto v = op.readOptional(sfz::Default::hiKey);
                    onNote = v.has_value();
                    hi = v.value_or(sfz::Default::hiKey);
                } else if (op.name == "key") {
                    const auto v = op.readOptional(sfz::Default::key);
                    onNote = v.has_value();
                    lo = hi = v.value_or(sfz::Default::key);
                }
            }
        };
        apply(global_);
        apply(master_);
        apply(group_);
        apply(opcodes);

        std::set<int> outputs;
        std::vector<int> routedKeys;
        if (onNote) {
            for (int n = std::max(lo, 0); n <= std::min(hi, 127); ++n) {
                if (outputForNote_[size_t(n)] > 0) {
                    outputs.insert(outputForNote_[size_t(n)]);
                    routedKeys.push_back(n);
                }
            }
        }
        if (outputs.empty()) {
            emit("region", opcodes, nullptr);  // stays on output 0
        } else if (outputs.size() == 1) {
            const std::string extra = "output=" + std::to_string(*outputs.begin()) + "\n";
            emit("region", opcodes, &extra);
            ++stats.routed;
        } else {
            // One region covers keys of several instruments (e.g. lokey=41 hikey=48): one copy per
            // routed key. Keys of the range that no instrument uses are never triggered by the engine.
            ++stats.split;
            for (int n : routedKeys) {
                const std::string extra = "lokey=" + std::to_string(n) + "\nhikey=" + std::to_string(n) +
                                          "\noutput=" + std::to_string(outputForNote_[size_t(n)]) + "\n";
                emit("region", opcodes, &extra);
                ++stats.routed;
            }
        }
    }

    void emit(const std::string& header, const std::vector<sfz::Opcode>& opcodes, const std::string* extra) {
        out << '<' << header << ">\n";
        for (const auto& op : opcodes) out << op.name << '=' << op.value << '\n';
        if (extra) out << *extra;
    }

    const std::array<int, 128>& outputForNote_;
    std::vector<sfz::Opcode> global_, master_, group_;
};

}  // namespace

bool routeSfzByKey(const std::string& sfzPath, const std::array<int, 128>& outputForNote, bool ramBased,
                   RoutedSfz& result, std::string* error) {
    RoutingListener listener(outputForNote);
    sfz::Parser parser;
    parser.setListener(&listener);
    listener.out << "// Generated by drums-engine from " << sfzPath << " (per-instrument outputs)\n";
    // A later <control> of the kit keeps this setting (it only resets default_path).
    if (ramBased) listener.out << "<control>\nhint_ram_based=1\n";
    parser.parseFile(sfzPath);
    if (parser.getErrorCount() > 0 || listener.stats.regions == 0) {
        if (error) {
            *error = listener.errors_.empty() ? "no regions found in " + sfzPath
                                              : sfzPath + ": " + listener.errors_.front();
        }
        return false;
    }
    result = listener.stats;
    result.text = listener.out.str();
    return true;
}

}  // namespace drums::engine
