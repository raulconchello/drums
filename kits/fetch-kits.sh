#!/usr/bin/env bash
# Downloads the free acoustic SFZ drum kits used by the engine into kits/<kit-name>/ and writes
# each kit's kit.json (instrument -> kit note map, license, source).
#
#   kits/fetch-kits.sh                 # all kits
#   kits/fetch-kits.sh avl-black-pearl # only some
#   kits/fetch-kits.sh --force ...     # re-download even if present
#
# Reproducible: the AVL zips are checked against pinned SHA-256 sums, SamsSonor is fetched at a
# pinned git commit. Needs curl, unzip, git, sha256sum. Kit folders are gitignored (kits/*/).
#
# Every kit here has only two real toms, so the generated drums-app.sfz wrapper adds a third
# ("tom2", kit note 102) by re-pitching the high tom's samples 3 semitones down. See README.md.
set -euo pipefail

KITS_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ALL_KITS=(avl-black-pearl avl-red-zeppelin sams-sonor)
FORCE=0
SELECTED=()
for arg in "$@"; do
    case "$arg" in
        --force) FORCE=1 ;;
        -h|--help) sed -n '2,14p' "$0"; exit 0 ;;
        *) SELECTED+=("$arg") ;;
    esac
done
[[ ${#SELECTED[@]} -eq 0 ]] && SELECTED=("${ALL_KITS[@]}")

for tool in curl unzip git sha256sum; do
    command -v "$tool" >/dev/null || { echo "error: '$tool' is required" >&2; exit 1; }
done

AVL_BASE="https://www.bandshed.net/sounds/AVLDrumkits_SFZ"
AVL_LICENSE="CC-BY-SA-3.0"
AVL_ATTRIB="AVL Drumkits by Glen MacArthur (AV Linux), https://www.bandshed.net/avldrumkits/"

# fetch_zip <dest-dir> <url> <sha256>: download, verify, unzip into dest-dir.
fetch_zip() {
    local dest="$1" url="$2" sha="$3" tmp
    tmp="$(mktemp -d)"
    echo "  downloading $url"
    if ! curl -fsSL --retry 3 -o "$tmp/kit.zip" "$url"; then
        rm -rf "$tmp"; echo "error: download failed: $url" >&2; return 1
    fi
    if ! echo "$sha  $tmp/kit.zip" | sha256sum -c --quiet -; then
        rm -rf "$tmp"; echo "error: checksum mismatch for $url" >&2; return 1
    fi
    mkdir -p "$dest"
    unzip -q -o "$tmp/kit.zip" -d "$dest"
    rm -rf "$tmp"
}

# AVL kits share one layout: 5 velocity layers per piece, GM-like keys 35-62, two toms
# (12" rack tom on 45, 16" floor tom on 41) plus their edge hits on 47/43.
write_avl_wrapper() {
    local dir="$1" sfz="$2" tomname="$3"
    cat > "$dir/drums-app.sfz" <<EOF
// Generated by kits/fetch-kits.sh for the drums app. Loads the original kit unchanged and adds
// a mid tom on key 102 (the kit has two toms): the ${tomname} samples tuned 3 semitones down.
#include "${sfz}"

<group> key=102 tune=-300 pan=-4 loop_mode=one_shot
<region> lovel=1 hivel=26 sample=45-${tomname}-1.wav
<region> lovel=27 hivel=52 sample=45-${tomname}-2.wav
<region> lovel=53 hivel=77 sample=45-${tomname}-3.wav
<region> lovel=78 hivel=102 sample=45-${tomname}-4.wav
<region> lovel=103 hivel=127 sample=45-${tomname}-5.wav
EOF
}

# write_kit_json <dir> <name> <sfz> <license> <source> <attribution>
AVL_NOTES='{
    "kick": 36, "snare": 38, "snareRim": 37,
    "hihatClosed": 42, "hihatOpen": 46, "hihatPedal": 44,
    "tom1": 45, "tom2": 102, "tom3": 41,
    "crash": 49, "ride": 51, "rideBell": 53
  }'
write_kit_json() {
    local dir="$1" name="$2" sfz="$3" license="$4" source="$5" attribution="$6" notes="$7"
    cat > "$dir/kit.json" <<EOF
{
  "name": "$name",
  "sfz": "$sfz",
  "notes": $notes,
  "hihatCC": 4,
  "license": "$license",
  "source": "$source",
  "attribution": "$attribution",
  "generatedBy": "kits/fetch-kits.sh"
}
EOF
}

fetch_avl() {
    local kit="$1" zip="$2" sha="$3" folder="$4" sfz="$5" title="$6" tomname="$7"
    local dir="$KITS_DIR/$kit"
    if [[ $FORCE -eq 0 && -f "$dir/$folder/$sfz" ]]; then
        echo "  already present (use --force to re-download)"
    else
        rm -rf "$dir"
        fetch_zip "$dir" "$AVL_BASE/$zip" "$sha"
    fi
    write_avl_wrapper "$dir/$folder" "$sfz" "$tomname"
    write_kit_json "$dir" "$title" "$folder/drums-app.sfz" "$AVL_LICENSE" "$AVL_BASE/$zip" \
        "$AVL_ATTRIB" "$AVL_NOTES"
}

fetch_sams_sonor() {
    local dir="$KITS_DIR/sams-sonor"
    local repo="https://github.com/sfzinstruments/SamsSonor.git"
    local commit="ef3e32058924ed1c3335e86d03094d3f310a9104"
    if [[ $FORCE -eq 0 && -f "$dir/SamsSonor.sfz" ]]; then
        echo "  already present (use --force to re-download)"
    else
        rm -rf "$dir"
        mkdir -p "$dir"
        echo "  fetching $repo @ $commit"
        git -C "$dir" init -q
        git -C "$dir" fetch -q --depth 1 "$repo" "$commit"
        git -C "$dir" -c advice.detachedHead=false checkout -q FETCH_HEAD
        rm -rf "$dir/.git"
    fi
    # Same opcodes as the kit's "Tom High" master/group, on key 102, tuned 3 semitones down.
    cat > "$dir/drums-app.sfz" <<'EOF'
// Generated by kits/fetch-kits.sh for the drums app. Loads the original kit unchanged and adds
// a mid tom on key 102 (the kit has two toms): the high tom samples tuned 3 semitones down.
#include "SamsSonor.sfz"

<master>
master_label=Tom Mid (derived)
locc22=1
amplitude_oncc22=200
pan_oncc29=100
pan_curvecc29=1
note_polyphony=1
off_time=2

<group>
key=102
tune=-300
group=50
group_volume=-4.5
<region> sample=TomHigh.flac lovel=1 hivel=60 amp_velcurve_60=1 offset_oncc98=324
<region> sample=TomHigh#1.flac lovel=61 hivel=85 amp_velcurve_85=1 offset_oncc98=462
<region> sample=TomHigh#2.flac lovel=86 hivel=105 amp_velcurve_105=1 offset_oncc98=492
<region> sample=TomHigh#3.flac lovel=106 hivel=110 amp_velcurve_110=1 offset_oncc98=420
<region> sample=TomHigh#4.flac lovel=111 hivel=127 amp_velcurve_127=1 offset_oncc98=501
EOF
    write_kit_json "$dir" "Sam's Sonor" "drums-app.sfz" "CC-BY-SA-4.0" \
        "$repo@$commit" \
        "Sam's Sonor Force 3001 samples by Sam Greene, SFZ mapping by kinwie (sfzinstruments)" '{
    "kick": 36, "snare": 38, "snareRim": 37,
    "hihatClosed": 42, "hihatOpen": 46, "hihatPedal": 44,
    "tom1": 45, "tom2": 102, "tom3": 43,
    "crash": 49, "ride": 51, "rideBell": 53
  }'
}

for kit in "${SELECTED[@]}"; do
    echo "== $kit"
    case "$kit" in
        avl-black-pearl)
            fetch_avl "$kit" BLACK_PEARL_2023_repack.zip \
                1ab43270ce4ea5d8794e98b158210a566e431d7e76646ef778ebabafba807609 \
                BLACK_PEARL_2023_repack Black_Pearl_2023_repack.sfz "AVL Black Pearl" "Pearl-12-Tom" ;;
        avl-red-zeppelin)
            fetch_avl "$kit" RED_ZEPPELIN_2023_repack.zip \
                9f5c5e5a76decae7eb63b2242f91a51210e91f7e5bb57587352c544721b1012f \
                RED_ZEPPELIN_2023_repack Red_Zeppelin_2023_repack.sfz "AVL Red Zeppelin" "Ludwig-14-Tom" ;;
        sams-sonor) fetch_sams_sonor ;;
        *) echo "error: unknown kit '$kit' (known: ${ALL_KITS[*]})" >&2; exit 1 ;;
    esac
    echo "  ok: $KITS_DIR/$kit/kit.json"
done
